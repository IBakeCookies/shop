CREATE TABLE language (
  code CHAR(2) PRIMARY KEY CHECK (code ~ '^[a-z]{2}$'),  -- ISO 639-1
  name TEXT NOT NULL UNIQUE,
  direction CHAR(3) NOT NULL CHECK (direction IN ('ltr', 'rtl'))
);

