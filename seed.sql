  cart_id UUID NOT NULL REFERENCES cart(id) ON DELETE CASCADE,
  product_variation_id INT NOT NULL REFERENCES product_variation(id),
  quantity INT NOT NULL CHECK (quantity > 0),
  price INT NOT NULL CHECK (price > 0),
  added_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (cart_id, product_variation_id)
);

CREATE OR REPLACE FUNCTION update_cart_expiration()
RETURNS TRIGGER AS $$
BEGIN
  NEW.expires_at = NEW.updated_at + INTERVAL '30 days';
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER cart_expiration_trigger
BEFORE INSERT OR UPDATE ON cart
FOR EACH ROW
EXECUTE FUNCTION update_cart_expiration();

